const byId = new Map(lexicon.map((l) => [l.id, l]));
const byForm = new Map<string, Lexeme[]>();
for (const l of lexicon) {
  for (const f of l.forms) byForm.set(f, [...(byForm.get(f) ?? []), l]);
}

export const lexemeById = (id: string) => byId.get(id);

/** Every entry a form can belong to: usually one, sometimes more (the text's senses decide). */
export const lexemesForForm = (form: string) => byForm.get(form) ?? [];

const posLabels: Record<PartOfSpeech, string> = {
  noun: 'noun',
  verb: 'verb',
  adj: 'adjective',
  adv: 'adverb',
  pron: 'pronoun',
  prep: 'preposition',
  conj: 'conjunction',
  num: 'number',
  part: 'particle',
  interj: 'interjection',
  name: 'name',
  phrase: 'phrase',
};
const genderLabels: Record<Gender, string> = { ma: 'masculine (animate)', mi: 'masculine (inanimate)', f: 'feminine', n: 'neuter' };
const aspectLabels: Record<Aspect, string> = { impf: 'imperfective', pf: 'perfective' };

/** "noun · feminine", "verb · perfective (partner: kupovat)". */
export function grammarLine(l: Lexeme) {
  return [
    posLabels[l.pos],
    l.gender ? genderLabels[l.gender] : null,
    l.aspect ? `${aspectLabels[l.aspect]}${l.partner ? ` (pair: ${l.partner})` : ''}` : null,
  ]
    .filter(Boolean)
    .join(' · ');
}
