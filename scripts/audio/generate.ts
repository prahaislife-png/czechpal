// Generates the A2 Academy's Czech recordings with Microsoft Azure neural voices (Vlasta, Antonín),
// once, into assets/audio/academy, and writes src/lib/academy/audio-manifest.ts. The app plays a
// file only when its text fingerprint still matches the app's text.
//
// Run through scripts/audio/generate.ps1, which asks for the key without showing or saving it:
//   AZURE_SPEECH_KEY, AZURE_SPEECH_REGION (e.g. westeurope)
// Options: --force (regenerate everything), --only=<key> (one recording).
import fs from 'node:fs';
import path from 'node:path';

import { audioHash, turnsOf } from '../../src/lib/academy/audio-key';
import { collectRecordings } from './collect';
import { checkVoices, speakersFor, VOICE } from './speakers';

const root = path.resolve(__dirname, '..', '..');
const outDir = path.join(root, 'assets', 'audio', 'academy');
const manifestFile = path.join(root, 'src', 'lib', 'academy', 'audio-manifest.ts');
const force = process.argv.includes('--force');
const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7);

/** A2 learners: a little slower than natural speech, as in the exam's clear recordings. */
const RATE = '-6%';
const PAUSE_MS = 450;

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function ssml(key: string, text: string) {
  const speakers = speakersFor(key)!;
  const parts = turnsOf(text).map((turn, i) => {
    const v = VOICE[speakers[i]];
    return `<voice name="${v.name}">${i ? `<break time="${PAUSE_MS}ms"/>` : ''}<prosody rate="${RATE}" pitch="${v.pitch}">${esc(turn)}</prosody></voice>`;
  });
  return `<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" xml:lang="cs-CZ">${parts.join('')}</speak>`;
}

function readManifest(): Record<string, string> {
  if (!fs.existsSync(manifestFile)) return {};
  const out: Record<string, string> = {};
  for (const m of fs.readFileSync(manifestFile, 'utf8').matchAll(/'([^']+)': \{ src: require\('[^']+'\), hash: '([0-9a-f]+)' \}/g)) out[m[1]] = m[2];
  return out;
}

function writeManifest(entries: { key: string; hash: string }[]) {
  const lines = entries
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((e) => `  '${e.key}': { src: require('../../../assets/audio/academy/${e.key}.mp3'), hash: '${e.hash}' },`);
  fs.writeFileSync(
    manifestFile,
    `/* eslint-disable @typescript-eslint/no-require-imports */
/**
 * Generated by scripts/audio/generate.ts: Czech recordings made with Microsoft Azure neural voices
 * (cs-CZ Vlasta and Antonín), one file per recording, with the fingerprint of the text it was
 * made from. Don't edit by hand; run the script again after changing a recording's text.
 */
export const recordings: Record<string, { src: number; hash: string }> = {
${lines.join('\n')}
};
`,
  );
}

async function synthesize(key: string, text: string, region: string, apiKey: string): Promise<Buffer> {
  for (let attempt = 1; attempt <= 5; attempt++) {
    const res = await fetch(`https://${region}.tts.speech.microsoft.com/cognitiveservices/v1`, {
      method: 'POST',
      headers: {
        'Ocp-Apim-Subscription-Key': apiKey,
        'Content-Type': 'application/ssml+xml',
        'X-Microsoft-OutputFormat': 'audio-24khz-48kbitrate-mono-mp3',
        'User-Agent': 'CzechLocal-audio-build',
      },
      body: ssml(key, text),
    });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    const detail = (await res.text().catch(() => '')).slice(0, 200);
    if (res.status === 401 || res.status === 403) throw new Error(`Azure refused the key (${res.status}). Check the key and the region. ${detail}`);
    if (res.status !== 429 && res.status < 500) throw new Error(`${key}: Azure error ${res.status} ${detail}`);
    await new Promise((r) => setTimeout(r, 2000 * attempt));
  }
  throw new Error(`${key}: Azure kept refusing (busy). Try again later.`);
}

async function main() {
  const all = collectRecordings();
  const problems = all.flatMap((r) => checkVoices(r.key, r.text));
  if (problems.length) {
    console.error('Fix the voices first (scripts/audio/voices.json):\n' + problems.join('\n'));
    process.exit(1);
  }
  const apiKey = process.env.AZURE_SPEECH_KEY;
  const region = process.env.AZURE_SPEECH_REGION;
  if (!apiKey || !region) {
    console.error('Set AZURE_SPEECH_KEY and AZURE_SPEECH_REGION (use scripts/audio/generate.ps1).');
    process.exit(1);
  }
  fs.mkdirSync(outDir, { recursive: true });
  const done = readManifest();
  const entries: { key: string; hash: string }[] = [];
  let made = 0;
  let chars = 0;
  for (const r of all) {
    const hash = audioHash(r.text);
    const file = path.join(outDir, `${r.key}.mp3`);
    const fresh = done[r.key] === hash && fs.existsSync(file);
    if ((only && r.key !== only) || (fresh && !force)) {
      if (fresh) entries.push({ key: r.key, hash });
      continue;
    }
    const audio = await synthesize(r.key, r.text, region, apiKey);
    fs.writeFileSync(file, audio);
    entries.push({ key: r.key, hash });
    made++;
    chars += r.text.length;
    process.stdout.write(`\r${made} made (${r.key})          `);
    // The free tier allows about 20 requests a minute.
    await new Promise((res) => setTimeout(res, 3100));
  }
  writeManifest(entries);
  console.log(`\nDone: ${made} recordings made (${chars.toLocaleString('en-GB')} characters), ${entries.length} in the app.`);
}

main().catch((e) => {
  console.error('\n' + (e instanceof Error ? e.message : String(e)));
  process.exit(1);
});
